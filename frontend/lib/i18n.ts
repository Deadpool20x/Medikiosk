const STRINGS: Record<PatientLang, PatientStrings> = { en, hi, gu };

export type PatientStringKey = keyof PatientStrings;

export function pt(
  lang: string | null | undefined,
  key: PatientStringKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = STRINGS[normLang(lang)][key] ?? STRINGS.en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}
